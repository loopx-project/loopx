"""CLI commands for PostgreSQL authority administration, schema/role setup, and genesis seed export."""
from __future__ import annotations

import argparse
import os
from collections.abc import Callable
from pathlib import Path

from ..control_plane.effect_runtime import effect_runtime_result
from ..paths import resolve_runtime_root
from ..control_plane.projects.registry_codec import load_registry


def register_postgres_commands(
    subparsers: argparse._SubParsersAction[argparse.ArgumentParser],
    add_subcommand_format: Callable[[argparse.ArgumentParser], None],
) -> None:
    parser = subparsers.add_parser(
        "postgres",
        help="PostgreSQL authority schema setup, restricted role assembly, and genesis seed export.",
    )
    add_subcommand_format(parser)
    actions = parser.add_subparsers(dest="postgres_action", required=True)

    # 1. setup: Admin PG Schema and restricted role assembly
    setup_parser = actions.add_parser(
        "setup",
        help="Explicitly assemble PostgreSQL schema, tables, RLS policies, metadata and optional restricted role.",
    )
    setup_parser.add_argument(
        "--database-url",
        default=os.environ.get("LOOPX_POSTGRES_URL", ""),
        help="PostgreSQL connection string (or LOOPX_POSTGRES_URL).",
    )
    setup_parser.add_argument(
        "--store-identity",
        help="Optional explicit store identity (postgresql:<32 lowercase hex>). Generated if omitted.",
    )
    setup_parser.add_argument(
        "--runtime-role",
        help="Optional restricted runtime role to assemble with least privileges.",
    )
    setup_parser.add_argument(
        "--execute",
        action="store_true",
        help="Execute the schema and role setup against the database.",
    )

    # 2. local-to-pg-seed / seed: Read-only local-to-pg-seed genesis snapshot sanitizer and exporter
    for seed_cmd in ("local-to-pg-seed", "seed"):
        seed_parser = actions.add_parser(
            seed_cmd,
            help="Export a local goal into a sanitized cursor=1 genesis seed (stripping expired leases, paths, .local/, Feishu IDs) and optionally seed target PG.",
        )
        seed_parser.add_argument("--goal-id", required=True, help="Goal ID to export.")
        seed_parser.add_argument(
            "--tenant-id",
            default="default",
            help="Target tenant ID for the PostgreSQL store (default: default).",
        )
        seed_parser.add_argument(
            "--database-url",
            default=os.environ.get("LOOPX_POSTGRES_URL", ""),
            help="Optional target PostgreSQL connection string for direct seeding.",
        )
        seed_parser.add_argument(
            "--store-identity",
            help="Optional PostgreSQL store identity for new database.",
        )
        seed_parser.add_argument(
            "--output",
            type=Path,
            help="Optional file path to write the sanitized genesis seed JSON.",
        )
        seed_parser.add_argument(
            "--execute",
            action="store_true",
            help="Execute the seed commit to target PostgreSQL; otherwise read-only preview/export.",
        )


def handle_postgres_command(
    args: argparse.Namespace,
    *,
    registry_path: Path,
    runtime_root_arg: str | None,
    print_payload: Callable[[dict[str, object], str, Callable[[dict[str, object]], str]], None],
    output_format: Callable[..., str],
) -> int | None:
    if args.command != "postgres":
        return None

    action = args.postgres_action
    if action == "setup":
        database_url = args.database_url or os.environ.get("LOOPX_POSTGRES_URL", "")
        if not database_url:
            payload = {
                "status": "failed",
                "reason": "--database-url or LOOPX_POSTGRES_URL environment variable is required for setup",
            }
            print_payload(payload, output_format(args), lambda v: f"Postgres setup: failed\n{v.get('reason')}")
            return 1

        if not args.execute:
            payload = {
                "status": "dry_run",
                "schema_version": "loopx_postgresql_authority_store_v0",
                "database_url_configured": bool(database_url),
                "store_identity": args.store_identity or "<auto-generated>",
                "runtime_role": args.runtime_role or None,
                "note": "Pass --execute to actually install schema and assemble roles in PostgreSQL",
            }
            print_payload(payload, output_format(args), lambda v: f"Postgres setup (dry-run):\n{v}")
            return 0

        request = {
            "databaseUrl": database_url,
            "storeIdentity": args.store_identity,
            "runtimeRole": args.runtime_role,
        }
        try:
            result = effect_runtime_result(
                "coordination.postgresql.setup", request, timeout=120.0, retry_safe=False
            )
        except Exception as error:
            result = {"status": "failed", "reason": str(error)}

        print_payload(
            result,
            output_format(args),
            lambda v: (
                f"PostgreSQL setup: {v.get('status')}\n"
                f"Schema version: {v.get('schema_version')}\n"
                f"Store identity: {v.get('store_identity')}\n"
                f"Runtime role: {v.get('runtime_role')}\n"
                f"{v.get('reason', '')}"
            ),
        )
        return 0 if result.get("status") == "installed" else 1

    elif action in ("local-to-pg-seed", "seed"):
        registry = load_registry(registry_path)
        resolved_root = str(resolve_runtime_root(registry, runtime_root_arg, registry_path=registry_path))

        database_url = args.database_url or os.environ.get("LOOPX_POSTGRES_URL", "")
        output_path = str(args.output.expanduser().resolve()) if args.output else None

        request = {
            "runtimeRoot": resolved_root,
            "goalId": args.goal_id,
            "tenantId": args.tenant_id,
            "outputPath": output_path,
            "databaseUrl": database_url if args.execute else None,
            "storeIdentity": args.store_identity,
            "execute": args.execute and bool(database_url),
        }
        try:
            result = effect_runtime_result(
                "coordination.postgresql.seed", request, timeout=180.0, retry_safe=False
            )
        except Exception as error:
            result = {"status": "failed", "reason": str(error)}

        print_payload(
            result,
            output_format(args),
            lambda v: (
                f"PostgreSQL genesis seed: {v.get('status')}\n"
                f"Goal: {v.get('goal_id')} (tenant: {v.get('tenant_id')})\n"
                f"Cursor: {v.get('cursor')} (revision: {v.get('provider_revision')})\n"
                f"Seed digest: {v.get('seed_digest')}\n"
                f"Output: {v.get('output_path') or 'memory'}\n"
                f"{v.get('reason', '')}"
            ),
        )
        return 0 if result.get("status") in ("exported", "seeded") else 1

    return None
