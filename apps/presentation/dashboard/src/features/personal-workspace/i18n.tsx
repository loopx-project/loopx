const messages: Record<WorkspaceLocale, Record<WorkspaceMessageKey, string>> = {
  en,
  "zh-CN": zhCN,
};

function formatMessage(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function readWorkspaceLocale(): WorkspaceLocale {
  try {
    const stored = window.localStorage.getItem(workspaceLocaleStorageKey);
    if (stored === "en" || stored === "zh-CN") return stored;
  } catch {
    // Browser preferences still apply when persistent storage is unavailable.
  }
  if (typeof navigator === "undefined") return "en";
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const language of languages) {
    const primaryLanguage = language?.split("-")[0].toLowerCase();
    if (primaryLanguage === "en") return "en";
    if (primaryLanguage === "zh") return "zh-CN";
  }
  return "en";
}

export type WorkspaceTranslate = (key: WorkspaceMessageKey, values?: Record<string, string | number>) => string;

export function WorkspaceI18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<WorkspaceLocale>(readWorkspaceLocale);

  function setLocale(nextLocale: WorkspaceLocale) {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(workspaceLocaleStorageKey, nextLocale);
    } catch {
      // Storage may be unavailable; the current session still updates immediately.
    }
  }

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<WorkspaceI18nValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => formatMessage(messages[locale][key], values),
  }), [locale]);

  return <WorkspaceI18nContext.Provider value={value}>{children}</WorkspaceI18nContext.Provider>;
}

export function useWorkspaceI18n(): WorkspaceI18nValue {
  const value = useContext(WorkspaceI18nContext);
  if (!value) {
    throw new Error("useWorkspaceI18n must be used within WorkspaceI18nProvider");
  }
  return value;
}

export function localizedGoalState(state: string, locale: WorkspaceLocale): string {
  const keyByState: Record<string, WorkspaceMessageKey> = {
    "安静运行": "state.quiet",
    "等你": "state.needsYou",
    "等待条件": "state.waiting",
    "已安排": "state.queued",
    "需修复": "state.needsRepair",
    "已完成": "state.completed",
    "已停止": "state.stopped",
  };
  const key = keyByState[state];
  return key ? messages[locale][key] : state;
}

